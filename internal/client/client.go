func ParseImport(raw string) (Import, error) {
	u, err := url.Parse(raw)
	if err != nil {
		return Import{}, err
	}
	if u.Scheme != "knockgate" || u.Host != "import" || !strings.HasPrefix(u.Path, "/v1") {
		return Import{}, errors.New("unsupported URL format")
	}
	q := u.Query()
	host := strings.TrimSpace(q.Get("host"))
	if host == "" {
		return Import{}, errors.New("missing host")
	}
	ports, err := parsePorts(q.Get("knock_ports"))
	if err != nil {
		return Import{}, fmt.Errorf("knock_ports: %w", err)
	}
	if len(ports) == 0 {
		return Import{}, errors.New("missing knock_ports")
	}
	secretText := q.Get("secret")
	if secretText == "" {
		return Import{}, errors.New("missing secret")
	}
	secret, err := base64.RawURLEncoding.DecodeString(secretText)
	if err != nil {
		return Import{}, fmt.Errorf("secret: %w", err)
	}
	targets, err := ParseTargets(q.Get("protected_ports"))
	if err != nil {
		return Import{}, fmt.Errorf("protected_ports: %w", err)
	}
	return Import{
		Label:          q.Get("label"),
		Host:           host,
		KnockPorts:     ports,
		ProtectedPorts: targets,
		Secret:         secret,
		SeqTimeout:     atoiDefault(q.Get("seq_timeout"), 10),
		OpenTimeout:    q.Get("open_timeout"),
		HMACWindow:     atoiDefault(q.Get("hmac_window"), 60),
	}, nil
}

func Knock(w io.Writer, imp Import, delay time.Duration) error {
	fmt.Fprintf(w, "UDP HMAC knocking %s: %s (delay %s)\n", imp.Host, joinInts(imp.KnockPorts), delay)
	for i, port := range imp.KnockPorts {
		payload := []byte(fmt.Sprintf("KG0|%d\n", i))
		if i == len(imp.KnockPorts)-1 {
			var err error
			payload, err = protocol.BuildCompact(imp.Secret, port, i, time.Now())
			if err != nil {
				return err
			}
		}
		addr := net.JoinHostPort(imp.Host, strconv.Itoa(port))
		conn, err := net.DialTimeout("udp", addr, 3*time.Second)
		if err != nil {
			return err
		}
		_, writeErr := conn.Write(payload)
		closeErr := conn.Close()
		if writeErr != nil {
			return writeErr
		}
		if closeErr != nil {
			return closeErr
		}
		fmt.Fprintf(w, "  -> step %d %d/udp\n", i, port)
		if i != len(imp.KnockPorts)-1 && delay > 0 {
			time.Sleep(delay)
		}
	}
	fmt.Fprintln(w, "Knock sent.")
	return nil
}

func CheckTargets(w io.Writer, host string, targets []Target, timeout time.Duration) {
	for _, target := range targets {
		switch target.Proto {
		case "udp":
			checkUDP(w, host, target, timeout)
		default:
			checkTCP(w, host, target, timeout)
		}
	}
}

func checkTCP(w io.Writer, host string, target Target, timeout time.Duration) {
	addr := net.JoinHostPort(host, strconv.Itoa(target.Port))
	conn, err := net.DialTimeout("tcp", addr, timeout)
	if err == nil {
		_ = conn.Close()
		fmt.Fprintf(w, "OPEN 端口已开 %s:%d/tcp\n", host, target.Port)
		return
	}
	if isRefused(err) {
		fmt.Fprintf(w, "REFUSED 端口已开 %s:%d/tcp\n", host, target.Port)
		return
	}
	if isTimeout(err) {
		fmt.Fprintf(w, "FILTERED 端口未开 %s:%d/tcp\n", host, target.Port)
		return
	}
	fmt.Fprintf(w, "FAILED 未知状态 %s:%d/tcp %v\n", host, target.Port, err)
}

func checkUDP(w io.Writer, host string, target Target, timeout time.Duration) {
	addr := net.JoinHostPort(host, strconv.Itoa(target.Port))
	conn, err := net.DialTimeout("udp", addr, timeout)
	if err != nil {
		fmt.Fprintf(w, "FAILED 未知状态 %s:%d/udp %v\n", host, target.Port, err)
		return
	}
	_, _ = conn.Write([]byte("knockgate-check"))
	_ = conn.Close()
	fmt.Fprintf(w, "UDP-SENT 未知状态 %s:%d/udp\n", host, target.Port)
}

func ServiceLoop(stdout, stderr io.Writer, opts Options, paths Paths) int {
	if opts.Interval < 10 {
		opts.Interval = DefaultInterval
	}
	ticker := time.NewTicker(time.Duration(opts.Interval) * time.Second)
	defer ticker.Stop()
	for {
		runServiceOnce(stdout, stderr, opts, paths)
		<-ticker.C
	}
}

func runServiceOnce(stdout, stderr io.Writer, opts Options, paths Paths) {
	imp, err := ParseImport(opts.ImportURL)
	if err != nil {
		logLine(stderr, "invalid import URL: %v", err)
		return
	}
	publicIP, err := DetectPublicIPv4(opts.IPCheckURLs, opts.IPCheckTimeout)
	if err != nil {
		logLine(stderr, "public IPv4 check failed: %v", err)
		return
	}
	if err := StrictPublicPath(imp.Host, firstPort(imp.KnockPorts), publicIP); err != nil {
		logLine(stderr, "skip knock: %v", err)
		return
	}
	last := strings.TrimSpace(readSmall(paths.LastIP))
	if last == publicIP {
		logLine(stdout, "public IP unchanged (%s), refreshing knock", publicIP)
	} else {
		logLine(stdout, "public IP changed: %s -> %s", emptyDash(last), publicIP)
	}
	if err := Knock(stdout, imp, opts.Delay); err != nil {
		logLine(stderr, "knock failed: %v", err)
		return
	}
	_ = os.MkdirAll(filepath.Dir(paths.LastIP), 0700)
	_ = os.WriteFile(paths.LastIP, []byte(publicIP+"\n"), 0600)
	if opts.CheckAfter && len(imp.ProtectedPorts) > 0 {
		CheckTargets(stdout, imp.Host, imp.ProtectedPorts, opts.CheckTimeout)
	}
}

func DetectPublicIPv4(urls []string, timeout time.Duration) (string, error) {
	if len(urls) == 0 {
		urls = DefaultIPCheckURLs
	}
	client := http.Client{Timeout: timeout}
	var errs []string
	for _, endpoint := range urls {
		endpoint = strings.TrimSpace(endpoint)
		if endpoint == "" {
			continue
		}
		ctx, cancel := context.WithTimeout(context.Background(), timeout)
		req, err := http.NewRequestWithContext(ctx, http.MethodGet, endpoint, nil)
		if err != nil {
			cancel()
			errs = append(errs, endpoint+": "+err.Error())
			continue
		}
		resp, err := client.Do(req)
		if err != nil {
			cancel()
			errs = append(errs, endpoint+": "+err.Error())
			continue
		}
		body, readErr := io.ReadAll(io.LimitReader(resp.Body, 4096))
		_ = resp.Body.Close()
		cancel()
		if readErr != nil {
			errs = append(errs, endpoint+": "+readErr.Error())
			continue
		}
		ip := firstIPv4(string(body))
		if ip == "" || suspiciousIPv4(ip) {
			errs = append(errs, endpoint+": no public IPv4")
			continue
		}
		return ip, nil
	}
	return "", errors.New(strings.Join(errs, "; "))
}

func StrictPublicPath(host string, port int, publicIP string) error {
	if net.ParseIP(publicIP) == nil || suspiciousIPv4(publicIP) {
		return fmt.Errorf("current address is not public IPv4: %s", publicIP)
	}
	ips, err := net.LookupIP(host)
	if err != nil {
		return fmt.Errorf("cannot resolve host %s: %w", host, err)
	}
	var resolved net.IP
	for _, ip := range ips {
		if v4 := ip.To4(); v4 != nil {
			resolved = v4
			break
		}
	}
	if resolved == nil {
		return fmt.Errorf("host has no IPv4 address: %s", host)
	}
	if suspiciousIPv4(resolved.String()) {
		return fmt.Errorf("%s resolved to private/CGNAT/fake/reserved IP %s", host, resolved)
	}
	ifaceName := routeInterfaceName(resolved.String(), port)
	if ifaceName != "" && suspiciousIface(ifaceName) {
		return fmt.Errorf("route to %s uses %s", host, ifaceName)
	}
	return nil
}

func WarnNetworkPath(w io.Writer, host string, port int) {
	ips, err := net.LookupIP(host)
	if err != nil {
		fmt.Fprintf(w, "WARN: cannot resolve %s: %v\n", host, err)
		return
	}
	var resolved string
	for _, ip := range ips {
		if v4 := ip.To4(); v4 != nil {
			resolved = v4.String()
			break
		}
	}
	if resolved == "" {
		return
	}
	if suspiciousIPv4(resolved) {
		fmt.Fprintf(w, "WARN: %s resolved to %s, which is private/CGNAT/fake-IP/reserved.\n", host, resolved)
		return
	}
	iface := routeInterfaceName(resolved, port)
	if iface != "" && suspiciousIface(iface) {
		fmt.Fprintf(w, "WARN: route to %s uses %s. TUN/VPN/proxy routing can make check results misleading.\n", host, iface)
	}
}

func DetectPlatform(requested string) (string, error) {
	if requested == "" || requested == "auto" {
		if fileExists("/etc/openwrt_release") && dirExists("/etc/init.d") {
			return "openwrt", nil
		}
		if dirExists("/opt/etc/init.d") && dirExists("/opt/bin") {
			return "asus-merlin", nil
		}
		if _, err := exec.LookPath("systemctl"); err == nil && (dirExists("/run/systemd/system") || commandOK("systemctl", "--version")) {
			return "systemd", nil
		}
		return "", errors.New("cannot auto-detect service manager; use --platform systemd, openwrt, or asus-merlin")
	}
	switch requested {
	case "systemd", "openwrt", "asus-merlin":
		return requested, nil
	default:
		return "", fmt.Errorf("unsupported platform: %s", requested)
	}
}

func PlatformPaths(platform string) (Paths, error) {
	switch platform {
	case "systemd":
		return Paths{Platform: platform, Bin: "/usr/local/bin/knockgate-client", Dir: "/etc/knockgate-client", Config: "/etc/knockgate-client/client.conf", LastIP: "/etc/knockgate-client/last_public_ip", Service: "/etc/systemd/system/" + ServiceName + ".service"}, nil
	case "openwrt":
		return Paths{Platform: platform, Bin: "/usr/bin/knockgate-client", Dir: "/etc/knockgate-client", Config: "/etc/knockgate-client/client.conf", LastIP: "/etc/knockgate-client/last_public_ip", Service: "/etc/init.d/" + ServiceName}, nil
	case "asus-merlin":
		return Paths{Platform: platform, Bin: "/opt/bin/knockgate-client", Dir: "/opt/etc/knockgate-client", Config: "/opt/etc/knockgate-client/client.conf", LastIP: "/opt/etc/knockgate-client/last_public_ip", Service: "/opt/etc/init.d/S99" + ServiceName, LogFile: "/opt/var/log/" + ServiceName + ".log"}, nil
	default:
		return Paths{}, fmt.Errorf("unsupported platform: %s", platform)
	}
}

func ExistingPaths() (Paths, error) {
	for _, platform := range []string{"systemd", "openwrt", "asus-merlin"} {
		paths, _ := PlatformPaths(platform)
		if fileExists(paths.Service) || fileExists(paths.Config) {
			return paths, nil
		}
	}
	platform, err := DetectPlatform("auto")
	if err != nil {
		return Paths{}, err
	}
	return PlatformPaths(platform)
}

func InstallService(paths Paths, opts Options) error {
	if err := os.MkdirAll(paths.Dir, 0700); err != nil {
		return err
	}
	self, err := os.Executable()
	if err != nil {
		return err
	}
	if err := copyFile(self, paths.Bin, 0755); err != nil {
		return err
	}
	if err := writeConfig(paths, opts); err != nil {
		return err
	}
	switch paths.Platform {
	case "systemd":
		if err := writeFile(paths.Service, systemdUnit(paths), 0644); err != nil {
			return err
		}
		if err := execCmd("systemctl", "daemon-reload"); err != nil {
			return err
		}
		return execCmd("systemctl", "enable", "--now", ServiceName+".service")
	case "openwrt":
		if err := writeFile(paths.Service, openwrtInit(paths), 0755); err != nil {
			return err
		}
		if err := execCmd(paths.Service, "enable"); err != nil {
			return err
		}
		return execCmd(paths.Service, "restart")
	case "asus-merlin":
		_ = os.MkdirAll("/opt/var/run", 0755)
		_ = os.MkdirAll("/opt/var/log", 0755)
		if err := writeFile(paths.Service, asusInit(paths), 0755); err != nil {
			return err
		}
		return execCmd(paths.Service, "restart")
	default:
		return fmt.Errorf("unsupported platform: %s", paths.Platform)
	}
}

func UninstallService(paths Paths) error {
	switch paths.Platform {
	case "systemd":
		_ = execCmd("systemctl", "disable", "--now", ServiceName+".service")
		_ = os.Remove(paths.Service)
		_ = execCmd("systemctl", "daemon-reload")
	case "openwrt":
		if fileExists(paths.Service) {
			_ = execCmd(paths.Service, "stop")
			_ = execCmd(paths.Service, "disable")
		}
		_ = os.Remove(paths.Service)
	case "asus-merlin":
		if fileExists(paths.Service) {
			_ = execCmd(paths.Service, "stop")
		}
		_ = os.Remove(paths.Service)
	}
	_ = os.Remove(paths.Bin)
	_ = os.RemoveAll(paths.Dir)
	return nil
}

func LoadServiceOptions(path string) (Options, Paths, error) {
	var paths Paths
	if path == "" {
		var err error
		paths, err = ExistingPaths()
		if err != nil {
			return Options{}, Paths{}, err
		}
		path = paths.Config
	} else {
		paths = Paths{Config: path, LastIP: filepath.Join(filepath.Dir(path), "last_public_ip")}
	}
	values, err := readConfig(path)
	if err != nil {
		return Options{}, Paths{}, err
	}
	if paths.Platform == "" {
		paths.Platform = values["PLATFORM"]
	}
	opts := Options{
		ImportURL:      values["URL"],
		Interval:       atoiDefault(values["INTERVAL"], DefaultInterval),
		IPCheckURLs:    splitCSV(strings.Split(values["IP_CHECK_URLS"], ",")),
		IPCheckTimeout: time.Duration(atoiDefault(values["IP_CHECK_TIMEOUT"], DefaultIPCheckSec)) * time.Second,
		CheckAfter:     values["CHECK_AFTER"] != "0",
		Delay:          parseDurationDefault(values["DELAY"], DefaultDelay),
		CheckTimeout:   parseDurationDefault(values["CHECK_TIMEOUT"], DefaultCheckTime),
	}
	if opts.ImportURL == "" {
		return Options{}, Paths{}, errors.New("missing URL in config")
	}
	if len(opts.IPCheckURLs) == 0 {
		opts.IPCheckURLs = DefaultIPCheckURLs
	}
	return opts, paths, nil
}

func writeConfig(paths Paths, opts Options) error {
	var b strings.Builder
	fmt.Fprintf(&b, "PLATFORM=%s\n", paths.Platform)
	fmt.Fprintf(&b, "URL=%s\n", opts.ImportURL)
	fmt.Fprintf(&b, "INTERVAL=%d\n", opts.Interval)
	fmt.Fprintf(&b, "IP_CHECK_URLS=%s\n", strings.Join(opts.IPCheckURLs, ","))
	fmt.Fprintf(&b, "IP_CHECK_TIMEOUT=%d\n", int(opts.IPCheckTimeout.Seconds()))
	if opts.CheckAfter {
		fmt.Fprintln(&b, "CHECK_AFTER=1")
	} else {
		fmt.Fprintln(&b, "CHECK_AFTER=0")
	}
	fmt.Fprintf(&b, "DELAY=%s\n", opts.Delay)
	fmt.Fprintf(&b, "CHECK_TIMEOUT=%s\n", opts.CheckTimeout)
	return writeFile(paths.Config, b.String(), 0600)
}

func readConfig(path string) (map[string]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	out := map[string]string{}
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		out[strings.TrimSpace(key)] = strings.TrimSpace(value)
	}
	return out, scanner.Err()
}

