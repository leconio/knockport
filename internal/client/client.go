func Main(args []string, version string, stdout, stderr io.Writer) int {
	name := filepath.Base(os.Args[0])
	if len(args) == 0 {
		args = []string{"knock"}
	}
	if args[0] == "-h" || args[0] == "--help" {
		Usage(stdout, name, version)
		return 0
	}
	cmd := args[0]
	if strings.HasPrefix(cmd, "-") {
		cmd = "knock"
	} else {
		args = args[1:]
	}

	switch cmd {
	case "knock":
		return runKnock(args, stdout, stderr)
	case "check":
		return runCheck(args, stdout, stderr)
	case "install":
		return runInstall(args, stdout, stderr)
	case "service-run":
		return runService(args, stdout, stderr)
	case "status":
		return runStatus(stdout, stderr)
	case "logs":
		return runLogs(stdout, stderr)
	case "uninstall":
		return runUninstall(stdout, stderr)
	case "help":
		Usage(stdout, name, version)
		return 0
	default:
		fmt.Fprintf(stderr, "Unknown command: %s\n", cmd)
		Usage(stderr, name, version)
		return 2
	}
}

func runKnock(args []string, stdout, stderr io.Writer) int {
	var checkPorts string
	var secretText string
	var verbose bool
	opts := Options{CheckAfter: true, Delay: DefaultDelay, CheckTimeout: DefaultCheckTime}
	fs := newFlagSet("knock", stderr)
	fs.StringVar(&opts.ImportURL, "url", "", "import URL")
	fs.StringVar(&secretText, "secret", "", "base64url HMAC secret")
	fs.StringVar(&checkPorts, "check-ports", "", "ports to check")
	fs.BoolFunc("no-check", "disable checks", func(string) error {
		opts.CheckAfter = false
		return nil
	})
	fs.Var(durationSecondsFlag{value: &opts.Delay}, "delay", "delay seconds")
	fs.Var(durationSecondsFlag{value: &opts.Delay}, "delay-seconds", "delay seconds")
	fs.Var(durationSecondsFlag{value: &opts.Delay}, "d", "delay seconds")
	fs.Var(durationSecondsFlag{value: &opts.CheckTimeout}, "timeout", "timeout seconds")
	fs.Var(durationSecondsFlag{value: &opts.CheckTimeout}, "timeout-seconds", "timeout seconds")
	fs.Var(durationSecondsFlag{value: &opts.CheckTimeout}, "t", "timeout seconds")
	fs.BoolVar(&verbose, "verbose", false, "verbose")
	fs.BoolVar(&verbose, "v", false, "verbose")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	_ = verbose

	var imp Import
	var err error
	if opts.ImportURL != "" {
		imp, err = ParseImport(opts.ImportURL)
		if err != nil {
			fmt.Fprintf(stderr, "Invalid import URL: %v\n", err)
			return 2
		}
	} else {
		rest := fs.Args()
		if secretText == "" || len(rest) < 2 {
			fmt.Fprintln(stderr, "Manual mode requires --secret SECRET SERVER KNOCK_PORT...")
			return 2
		}
		secret, err := base64.RawURLEncoding.DecodeString(secretText)
		if err != nil {
			fmt.Fprintf(stderr, "Invalid secret: %v\n", err)
			return 2
		}
		ports, err := parsePorts(strings.Join(rest[1:], ","))
		if err != nil {
			fmt.Fprintf(stderr, "Invalid knock ports: %v\n", err)
			return 2
		}
		imp = Import{Host: rest[0], KnockPorts: ports, Secret: secret}
	}
	targets := imp.ProtectedPorts
	if checkPorts != "" {
		targets, err = ParseTargets(checkPorts)
		if err != nil {
			fmt.Fprintf(stderr, "Invalid check ports: %v\n", err)
			return 2
		}
	}
	WarnNetworkPath(stdout, imp.Host, firstPort(imp.KnockPorts))
	if err := Knock(stdout, imp, opts.Delay); err != nil {
		fmt.Fprintf(stderr, "Knock failed: %v\n", err)
		return 1
	}
	if opts.CheckAfter && len(targets) > 0 {
		CheckTargets(stdout, imp.Host, targets, opts.CheckTimeout)
	}
	return 0
}

func runCheck(args []string, stdout, stderr io.Writer) int {
	timeout := DefaultCheckTime
	var verbose bool
	fs := newFlagSet("check", stderr)
	fs.Var(durationSecondsFlag{value: &timeout}, "timeout", "timeout seconds")
	fs.Var(durationSecondsFlag{value: &timeout}, "timeout-seconds", "timeout seconds")
	fs.Var(durationSecondsFlag{value: &timeout}, "t", "timeout seconds")
	fs.BoolVar(&verbose, "verbose", false, "verbose")
	fs.BoolVar(&verbose, "v", false, "verbose")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	_ = verbose
	rest := fs.Args()
	if len(rest) < 2 {
		fmt.Fprintln(stderr, "Usage: knockgate-client check SERVER PORT[/tcp|/udp]...")
		return 2
	}
	targets, err := ParseTargets(strings.Join(rest[1:], ","))
	if err != nil {
		fmt.Fprintf(stderr, "Invalid check ports: %v\n", err)
		return 2
	}
	WarnNetworkPath(stdout, rest[0], firstTargetPort(targets))
	CheckTargets(stdout, rest[0], targets, timeout)
	return 0
}

func runInstall(args []string, stdout, stderr io.Writer) int {
	opts := Options{Interval: DefaultInterval, IPCheckURLs: DefaultIPCheckURLs, IPCheckTimeout: DefaultIPCheckSec * time.Second, CheckAfter: true, Delay: DefaultDelay, CheckTimeout: DefaultCheckTime, Platform: "auto"}
	var ipURLs multiFlag
	var ipURLCSV string
	fs := newFlagSet("install", stderr)
	fs.StringVar(&opts.ImportURL, "url", "", "import URL")
	fs.IntVar(&opts.Interval, "interval", DefaultInterval, "interval")
	fs.Var(&ipURLs, "ip-check-url", "public IP check URL")
	fs.StringVar(&ipURLCSV, "ip-check-urls", "", "public IP check URLs")
	fs.Var(durationSecondsFlag{value: &opts.IPCheckTimeout}, "ip-check-timeout", "IP check timeout seconds")
	fs.StringVar(&opts.Platform, "platform", "auto", "platform")
	fs.BoolFunc("no-check", "disable checks", func(string) error {
		opts.CheckAfter = false
		return nil
	})
	fs.Var(durationSecondsFlag{value: &opts.Delay}, "delay", "delay seconds")
	fs.Var(durationSecondsFlag{value: &opts.Delay}, "delay-seconds", "delay seconds")
	fs.Var(durationSecondsFlag{value: &opts.Delay}, "d", "delay seconds")
	fs.Var(durationSecondsFlag{value: &opts.CheckTimeout}, "timeout", "timeout seconds")
	fs.Var(durationSecondsFlag{value: &opts.CheckTimeout}, "timeout-seconds", "timeout seconds")
	fs.Var(durationSecondsFlag{value: &opts.CheckTimeout}, "t", "timeout seconds")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if opts.ImportURL == "" {
		fmt.Fprintln(stderr, "install requires --url.")
		return 2
	}
	if opts.Interval < 10 {
		fmt.Fprintln(stderr, "Invalid interval: use at least 10 seconds.")
		return 2
	}
	if _, err := ParseImport(opts.ImportURL); err != nil {
		fmt.Fprintf(stderr, "Invalid import URL: %v\n", err)
		return 2
	}
	if len(ipURLs) > 0 || ipURLCSV != "" {
		opts.IPCheckURLs = splitCSV(append(strings.Split(ipURLCSV, ","), ipURLs...))
	}
	if os.Geteuid() != 0 {
		fmt.Fprintln(stderr, "install must run as root.")
		return 1
	}
	platform, err := DetectPlatform(opts.Platform)
	if err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	paths, err := PlatformPaths(platform)
	if err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	if err := InstallService(paths, opts); err != nil {
		fmt.Fprintf(stderr, "Install failed: %v\n", err)
		return 1
	}
	fmt.Fprintf(stdout, "Installed KnockGate client service (%s).\nConfig: %s\nCommand: %s\n", platform, paths.Config, paths.Bin)
	return 0
}

func runService(args []string, stdout, stderr io.Writer) int {
	var cfgPath string
	fs := newFlagSet("service-run", stderr)
	fs.StringVar(&cfgPath, "config", "", "config path")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	opts, paths, err := LoadServiceOptions(cfgPath)
	if err != nil {
		fmt.Fprintf(stderr, "Load config failed: %v\n", err)
		return 1
	}
	return ServiceLoop(stdout, stderr, opts, paths)
}

