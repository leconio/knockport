func asusInit(paths Paths) string {
	return fmt.Sprintf(`#!/bin/sh
PID_FILE=/opt/var/run/%s.pid
LOG_FILE=%s

case "$1" in
	start)
		if [ -f "$PID_FILE" ] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; then
			exit 0
		fi
		%s service-run --config %s >>"$LOG_FILE" 2>&1 &
		echo $! >"$PID_FILE"
		;;
	stop)
		if [ -f "$PID_FILE" ]; then
			kill "$(cat "$PID_FILE")" 2>/dev/null || true
			rm -f "$PID_FILE"
		fi
		;;
	restart)
		"$0" stop
		sleep 1
		"$0" start
		;;
	status)
		if [ -f "$PID_FILE" ] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; then
			echo "running"
		else
			echo "stopped"
			exit 1
		fi
		;;
	*)
		echo "Usage: $0 {start|stop|restart|status}"
		exit 1
		;;
esac
`, ServiceName, paths.LogFile, paths.Bin, paths.Config)
}

func runServiceCommand(stdout, stderr io.Writer, paths Paths, command string) int {
	switch paths.Platform {
	case "systemd":
		return execStream(stdout, stderr, "systemctl", command, ServiceName+".service")
	case "openwrt", "asus-merlin":
		return execStream(stdout, stderr, paths.Service, command)
	default:
		fmt.Fprintf(stderr, "Unsupported platform: %s\n", paths.Platform)
		return 1
	}
}

func execStream(stdout, stderr io.Writer, name string, args ...string) int {
	cmd := exec.Command(name, args...)
	cmd.Stdout = stdout
	cmd.Stderr = stderr
	if err := cmd.Run(); err != nil {
		return 1
	}
	return 0
}

func execCmd(name string, args ...string) error {
	cmd := exec.Command(name, args...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("%s %s failed: %w: %s", name, strings.Join(args, " "), err, strings.TrimSpace(string(out)))
	}
	return nil
}

func commandOK(name string, args ...string) bool {
	return exec.Command(name, args...).Run() == nil
}

func copyFile(src, dst string, mode os.FileMode) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	if err := os.MkdirAll(filepath.Dir(dst), 0755); err != nil {
		return err
	}
	out, err := os.OpenFile(dst, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, mode)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		_ = out.Close()
		return err
	}
	if err := out.Close(); err != nil {
		return err
	}
	return os.Chmod(dst, mode)
}

func writeFile(path, text string, mode os.FileMode) error {
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(text), mode); err != nil {
		return err
	}
	return os.Chmod(path, mode)
}

func parsePorts(text string) ([]int, error) {
	var out []int
	for _, item := range strings.Split(text, ",") {
		item = strings.TrimSpace(item)
		if item == "" {
			continue
		}
		p, err := strconv.Atoi(item)
		if err != nil || p < 1 || p > 65535 {
			return nil, fmt.Errorf("invalid port %q", item)
		}
		out = append(out, p)
	}
	return out, nil
}

func ParseTargets(text string) ([]Target, error) {
	var out []Target
	for _, item := range strings.Split(text, ",") {
		item = strings.TrimSpace(item)
		if item == "" {
			continue
		}
		portText, proto, ok := strings.Cut(item, "/")
		if !ok {
			proto = "tcp"
		}
		proto = strings.ToLower(strings.TrimSpace(proto))
		if proto != "tcp" && proto != "udp" {
			return nil, fmt.Errorf("invalid protocol %q", proto)
		}
		p, err := strconv.Atoi(strings.TrimSpace(portText))
		if err != nil || p < 1 || p > 65535 {
			return nil, fmt.Errorf("invalid port %q", portText)
		}
		out = append(out, Target{Port: p, Proto: proto})
	}
	return out, nil
}

func splitCSV(values []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, value := range values {
		for _, item := range strings.Split(value, ",") {
			item = strings.TrimSpace(item)
			if item != "" && !seen[item] {
				seen[item] = true
				out = append(out, item)
			}
		}
	}
	return out
}

func atoiDefault(text string, fallback int) int {
	n, err := strconv.Atoi(strings.TrimSpace(text))
	if err != nil {
		return fallback
	}
	return n
}

func parseDurationDefault(text string, fallback time.Duration) time.Duration {
	if text == "" {
		return fallback
	}
	if d, err := parseFlexibleDuration(text); err == nil {
		return d
	}
	return fallback
}

func parseFlexibleDuration(text string) (time.Duration, error) {
	text = strings.TrimSpace(text)
	if text == "" {
		return 0, errors.New("empty duration")
	}
	if d, err := time.ParseDuration(text); err == nil {
		return d, nil
	}
	f, err := strconv.ParseFloat(text, 64)
	if err != nil {
		return 0, err
	}
	return time.Duration(f * float64(time.Second)), nil
}

func firstIPv4(text string) string {
	re := regexp.MustCompile(`(?:\d{1,3}\.){3}\d{1,3}`)
	for _, match := range re.FindAllString(text, -1) {
		ip := net.ParseIP(match)
		if ip != nil && ip.To4() != nil {
			return ip.To4().String()
		}
	}
	return ""
}

func suspiciousIPv4(ipText string) bool {
	ip := net.ParseIP(ipText).To4()
	if ip == nil {
		return true
	}
	a, b := ip[0], ip[1]
	switch {
	case a == 0, a == 10, a == 127:
		return true
	case a == 100 && b >= 64 && b <= 127:
		return true
	case a == 169 && b == 254:
		return true
	case a == 172 && b >= 16 && b <= 31:
		return true
	case a == 192 && b == 0:
		return true
	case a == 192 && b == 168:
		return true
	case a == 198 && (b == 18 || b == 19):
		return true
	case a >= 224:
		return true
	default:
		return false
	}
}

func routeInterfaceName(ipText string, port int) string {
	if port <= 0 {
		port = 53
	}
	conn, err := net.DialTimeout("udp", net.JoinHostPort(ipText, strconv.Itoa(port)), time.Second)
	if err != nil {
		return ""
	}
	local, _ := conn.LocalAddr().(*net.UDPAddr)
	_ = conn.Close()
	if local == nil {
		return ""
	}
	ifaces, err := net.Interfaces()
	if err != nil {
		return ""
	}
	for _, iface := range ifaces {
		addrs, err := iface.Addrs()
		if err != nil {
			continue
		}
		for _, addr := range addrs {
			if containsIP(addr, local.IP) {
				return iface.Name
			}
		}
	}
	return ""
}

func containsIP(addr net.Addr, ip net.IP) bool {
	switch v := addr.(type) {
	case *net.IPNet:
		return v.Contains(ip)
	case *net.IPAddr:
		return v.IP.Equal(ip)
	default:
		return false
	}
}

func suspiciousIface(name string) bool {
	name = strings.ToLower(name)
	prefixes := []string{"tun", "tap", "utun", "wg", "tailscale", "zt", "clash", "mihomo", "sing", "vpn"}
	for _, p := range prefixes {
		if strings.HasPrefix(name, p) {
			return true
		}
	}
	return false
}

func isRefused(err error) bool {
	text := strings.ToLower(err.Error())
	return strings.Contains(text, "connection refused") || strings.Contains(text, "actively refused")
}

func isTimeout(err error) bool {
	var ne net.Error
	if errors.As(err, &ne) && ne.Timeout() {
		return true
	}
	text := strings.ToLower(err.Error())
	return strings.Contains(text, "timeout") || strings.Contains(text, "i/o timeout")
}

